describe("Bookshelf geometry", function()
    it("caps variable cover height at the shelf book height", function()
        ZenSpec.replace("device", { screen = { scaleBySize = function(_self, n) return n end } })
        ZenSpec.replace("modules/filebrowser/folder_cover", { isBook = function() return true end })
        ZenSpec.replace("bookinfomanager", { getBookInfo = function() return { cover_w = 20, cover_h = 100 } end })
        ZenSpec.unload("modules/filebrowser/bookshelf_layout")
        local shelf = require("modules/filebrowser/bookshelf_layout")
        shelf.bind({ config = { bookshelf_layout = { simplified_version = 12, mode = "covers", uniform_height = false } } })
        local menu = { item_height = 100 }
        local _i, height = shelf.metrics(menu, { file = "book.epub" }, 1)
        assert.are.equal(shelf.bookHeight(menu), height)
        ZenSpec.unload("modules/filebrowser/bookshelf_layout")
    end)
end)
