describe("stats page layout settings", function()
    it("defaults to the tabs layout and counting omnibus works", function()
        local StatsSettings = require("modules/filebrowser/patches/stats_settings")
        local settings = StatsSettings.normalize({})
        assert.are.equal("tabs", settings.layout)
        assert.is_true(settings.count_omnibus)
    end)

    it("keeps the dashboard layout and a disabled omnibus count", function()
        local StatsSettings = require("modules/filebrowser/patches/stats_settings")
        local settings = StatsSettings.normalize({ layout = "dashboard", count_omnibus = false })
        assert.are.equal("dashboard", settings.layout)
        assert.is_false(settings.count_omnibus)
        assert.are.equal("tabs", StatsSettings.normalize({ layout = "other" }).layout)
    end)
end)
